def _artifact_reference_manifest(oncoref) -> pd.DataFrame:
    """Return the compact manifest for the artifact-backed expression view.

    The summary-row availability API is gene-independent but not lightweight:
    oncoref 1.8.132 builds it by materializing the roughly five-million-row
    reference summary.  Artifact build metadata is a small CSV emitted beside
    the percentile shards and contains the exact source identity and sample
    count served by ``reference_source="artifact"``.

    Current bundles require one metadata row per percentile shard.  Older
    supported bundles that lack the sidecar fall back to artifact availability,
    whose implementation enumerates shard filenames and never touches the
    summary expression frame.
    """
    metadata_accessor = getattr(
        oncoref, "expression_artifact_build_metadata", None
    )
    shard_accessor = getattr(oncoref, "available_percentile_cohorts", None)
    if callable(metadata_accessor) and callable(shard_accessor):
        # Enumerating shards ensures the released bundle is present. Reading
        # optional metadata first on a cold install returns an empty frame;
        # caching the ensuing compatibility fallback then permanently omits
        # valid direct cohorts such as NBL, MTC, and SARC_MYXLPS in that process.
        available_codes = frozenset(str(code) for code in shard_accessor())
        metadata = metadata_accessor(auto_fetch=False, on_missing="empty")
        if {"cancer_code", "source_cohort"}.issubset(metadata.columns):
            manifest = metadata[
                metadata["cancer_code"].astype(str).isin(available_codes)
            ].copy()
            metadata_codes = frozenset(manifest["cancer_code"].astype(str))
            if metadata_codes == available_codes:
                if "n_cohort_samples" in manifest.columns:
                    manifest["n_samples"] = pd.to_numeric(
                        manifest["n_cohort_samples"], errors="coerce"
                    )
                manifest["available"] = True
                return manifest

    availability_accessor = getattr(
        oncoref, "cancer_reference_expression_availability", None
    )
    if not callable(availability_accessor):
        raise AttributeError("oncoref has no artifact manifest accessor")
    # ``sample_qc='artifact'`` is not accepted by the availability API in
    # oncoref 1.8.x.  Availability under ``pass`` still means the percentile
    # shard exists; trufflepig reads that shard under its recorded build policy.
    return availability_accessor(
        normalize="tpm_clean",
        reference_source="artifact",
        sample_qc="pass",
    )


def _parse_pan_value_column(col: str) -> tuple[str, int] | None:
    """Return ``(trufflepig_column, priority)`` for expression value columns.

    Trufflepig follows the pirlygenes 5.2 entity-first surface and keeps
    both raw and technical-RNA-clean views explicit:
    ``<tissue>_nTPM_raw`` / ``<cancer>_TPM_raw`` and
    ``<tissue>_nTPM_clean`` / ``<cancer>_TPM_clean``.
    """
    if col.startswith("tcga_"):
        return "", 0
    legacy_unit_prefixes = (
        "nTPM_clean_",
        "TPM_clean_",
        "nTPM_raw_",
        "TPM_raw_",
        "nTPM_",
        "TPM_",
        "FPKM_",
    )
    if col.startswith(legacy_unit_prefixes):
        raise ValueError(
            "pirlygenes returned a legacy unit-prefix expression column "
            f"{col!r}; trufflepig requires entity-first columns like "
            "'PRAD_TPM_clean'"
        )
    # Recognized normalized/provenance variants that should not leak through.
    drop_suffixes = (
        "_nTPM_hk",
        "_TPM_hk",
        "_nTPM_percentile",
        "_TPM_percentile",
        "_FPKM",
    )
    if col.endswith(drop_suffixes):
        return "", 0

    suffix_rules = (
        ("_nTPM_clean", "_nTPM_clean", 40),
        ("_TPM_clean", "_TPM_clean", 40),
        ("_nTPM_raw", "_nTPM_raw", 30),
        ("_TPM_raw", "_TPM_raw", 30),
        ("_nTPM", "_nTPM_raw", 20),
        ("_TPM", "_TPM_raw", 20),
    )
    for source_suffix, target_suffix, priority in suffix_rules:
        if col.endswith(source_suffix):
            return f"{col[: -len(source_suffix)]}{target_suffix}", priority
    return None


def _standardize_pan_cancer_columns(df: pd.DataFrame) -> pd.DataFrame:
    """Convert pirlygenes' pan-cancer frame to trufflepig's stable schema."""
    selected: dict[str, tuple[int, str, int]] = {}
    non_value_cols: list[str] = []
    for position, col in enumerate(df.columns):
        parsed = _parse_pan_value_column(str(col))
        if parsed is None:
            non_value_cols.append(col)
            continue
        target, priority = parsed
        if not target:
            continue
        old = selected.get(target)
        if old is None or priority > old[0]:
            selected[target] = (priority, col, position)

    ordered_targets = sorted(selected, key=lambda target: selected[target][2])
    columns = {col: df[col] for col in non_value_cols}
    for target in ordered_targets:
        _priority, source, _position = selected[target]
        columns[target] = df[source]
    # Analysis-facing aliases (`*_TPM`, `*_nTPM`) intentionally shadow the
    # "raw" semantics they had under pirlygenes 5.1 — they now point at the
    # technical-RNA-clean columns so every analysis path sees the same
    # sanitized values. Callers that need raw must read `*_TPM_raw` /
    # `*_nTPM_raw` explicitly.
    for target in ordered_targets:
        if target.endswith("_TPM_clean"):
            alias = target.removesuffix("_clean")
        elif target.endswith("_nTPM_clean"):
            alias = target.removesuffix("_clean")
        else:
            continue
        columns.setdefault(alias, df[selected[target][1]])
    return pd.DataFrame(columns, index=df.index).copy()


def _canonicalize_cancer_code_column(df: pd.DataFrame) -> pd.DataFrame:
    """Resolve the ``cancer_code`` column through pirlygenes' alias resolver.

    The bundled deconvolved artifacts predate pirlygenes' Phase-C code renames
    (e.g. ``CHON``→``SARC_CHON``), so a sample looked up by its *new* registry
    code would silently miss its subtype reference and fall back to broad SARC.
    Canonicalizing on load — using the now-shipped ``CANCER_TYPE_ALIASES`` — keeps
    the artifact correct without a regeneration and auto-absorbs future rename
    waves. Codes with no alias (legacy cohort-name leakage like ``BEATAML`` /
    ``TARGET_*``, a separate data-gen issue) are left unchanged. See #53.
    """
    if "cancer_code" not in df.columns:
        return df
    from trufflepig.cancer_ontology import resolve_cancer_type

    def _resolve(code: str) -> str:
        try:
            return resolve_cancer_type(code)
        except Exception:
            return code

    uniques = df["cancer_code"].dropna().astype(str).unique()
    mapping = {code: _resolve(code) for code in uniques}
    df["cancer_code"] = df["cancer_code"].map(
        lambda c: mapping.get(str(c), c) if pd.notna(c) else c
    )
    return df



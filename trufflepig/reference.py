_SUBTYPE_DECONV_PATH = TRUFFLEPIG_DATA_DIR / "subtype-deconvolved-expression.csv.gz"
_TUMOR_UP_MATCHED_NORMAL_PATH = TRUFFLEPIG_DATA_DIR / "tumor-up-vs-matched-normal.csv"

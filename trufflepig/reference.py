"""Expression-backed reference data for the analysis engine.

Pirlygenes owns the ID-keyed pan-cancer/HPA reference matrix and the
normalization primitives. Trufflepig owns deconvolved tumor-only
artifacts generated by its decomposition code. The public trufflepig
surface exposes normalized ``<CODE>_TPM`` cohort columns by default and
keeps symbol-level deconvolved references behind explicit accessors.
"""


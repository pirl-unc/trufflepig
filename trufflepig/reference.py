def _apply_trufflepig_pan_normalize(
    df: pd.DataFrame,
    normalize,
    log_transform: bool,
) -> pd.DataFrame:
    value_cols = _analysis_value_cols(df)
    if isinstance(normalize, (list, tuple, set)):
        modes = {str(mode).lower() for mode in normalize}
        if modes <= {"tpm", "tpm_clean"}:
            normalize = "tpm_clean"
        elif "housekeeping" in modes or "hk" in modes:
            normalize = "housekeeping"
        elif "percentile" in modes:
            normalize = "percentile"
    if normalize is None or normalize in {"tpm", "TPM", "tpm_clean"}:
        out = df
    elif normalize in {"housekeeping", "hk"}:
        out = _pirlygenes.normalize_to_housekeeping(df, value_cols=value_cols)
    elif normalize == "percentile":
        out, _ = _pirlygenes.percentile_rank_expression(df, value_cols=value_cols)
    else:
        raise ValueError(
            "normalize must be None, 'tpm', 'tpm_clean', 'housekeeping', "
            "'hk', or 'percentile'; "
            f"got {normalize!r}"
        )
    if log_transform:
        out = _pirlygenes.log2_transform(out, value_cols=value_cols)
    return out


def _load_pan_cancer_from_pirlygenes(
    *,
    genes_tuple,
    remove_noncoding: bool,
) -> pd.DataFrame:
    # Trufflepig pins pirlygenes>=5.2,<6 (see pyproject.toml), which provides
    # the entity-first ``normalize=["tpm", "tpm_clean"]`` preset and clean
    # TPM columns by default. Earlier pirlygenes APIs are not supported.
    if remove_noncoding:
        return _pirlygenes.pan_cancer_expression(
            genes=genes_tuple,
            normalize=["tpm", "tpm_clean"],
            technical_rna_normalize=True,
            remove_noncoding=True,
            renormalize_to_million=True,
        )
    return _pirlygenes.pan_cancer_expression(
        genes=genes_tuple,
        normalize=["tpm", "tpm_clean"],
    )


def _pan_cancer_cache_key(
    genes,
    normalize,
    log_transform,
    technical_rna_normalize,
    remove_noncoding,
) -> tuple:
    genes_tuple = None if genes is None else tuple(genes)
    genes_key = (
        None
        if genes_tuple is None
        else frozenset(str(g).upper() for g in genes_tuple)
    )
    cache_key = (
        genes_key,
        tuple(normalize) if isinstance(normalize, list) else normalize,
        bool(log_transform),
        bool(technical_rna_normalize),
        bool(remove_noncoding),
    )
    return cache_key, genes_tuple


@lru_cache(maxsize=None)
def _tcga_deconvolved_normalized(
    technical_rna_normalize: bool,
    remove_noncoding: bool,
) -> pd.DataFrame:
    """Build + validate the normalized TCGA-deconvolved frame once per worker.

    The normalize -> renormalize -> assert pipeline over the ~640k-row artifact
    costs ~3.5s and is a pure function of the (cached) raw read plus the two
    bool args, so memoize it — callers were re-running it on every call. The
    public wrapper returns a ``.copy()`` to keep the fresh-object contract.
    """
    df = _tcga_deconvolved_expression_cached().copy()
    df, _ = _pirlygenes.normalize_expression(
        df,
        label_col="symbol",
        id_col="Ensembl_Gene_ID" if "Ensembl_Gene_ID" in df.columns else None,
        value_cols=_DECONV_VALUE_COLS,
        group_cols=("cancer_code",),
        remove_noncoding=remove_noncoding,
    )
    df = _renormalize_long_groups_to_million(
        df,
        value_cols=_DECONV_VALUE_COLS,
        group_cols=("cancer_code",),
    )
    assert_clean_tpm(
        df,
        value_cols=_DECONV_VALUE_COLS,
        label_col="symbol",
        id_col="Ensembl_Gene_ID" if "Ensembl_Gene_ID" in df.columns else None,
        context="tcga_deconvolved_expression",
    )
    return df


def tcga_deconvolved_expression(
    technical_rna_normalize: bool = False,
    remove_noncoding: bool = False,
) -> pd.DataFrame:
    """Per-(gene, TCGA code) tumor-only TPM medians from offline deconv.

    The current bundled artifact includes ``Ensembl_Gene_ID`` when it can be
    recovered unambiguously from the source reference. Historical rows for
    duplicated symbols remain symbol-keyed until the offline generator is rerun
    with the new ID-preserving schema. Trufflepig always exposes the artifact
    on the standard TPM-1e6 footing.
    """
    return _tcga_deconvolved_normalized(
        technical_rna_normalize, remove_noncoding
    ).copy()



def _filter_cancer_code(df: pd.DataFrame, cancer_code: str | None) -> pd.DataFrame:
    if cancer_code is None:
        return df.reset_index(drop=True)
    code = str(cancer_code).upper()
    return df[df["cancer_code"].astype(str).str.upper() == code].reset_index(drop=True)


def _renormalize_long_groups_to_million(
    df: pd.DataFrame,
    *,
    value_cols: tuple[str, ...],
    group_cols: tuple[str, ...],
    reference_col: str | None = None,
) -> pd.DataFrame:
    out = df.copy()
    if not value_cols:
        return out
    reference_col = reference_col or value_cols[0]
    groupers = [out[col] for col in group_cols]
    reference_values = pd.to_numeric(out[reference_col], errors="coerce")
    totals = reference_values.groupby(groupers, dropna=False).transform("sum")
    mask = totals > 0
    scales = 1_000_000.0 / totals.where(mask)
    for col in value_cols:
        values = pd.to_numeric(out[col], errors="coerce")
        out[col] = values.where(~mask, values * scales)
    return out


